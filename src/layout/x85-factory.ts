// Factory keymaps of the X85 Pro, used to flag keys the owner has remapped.
// Base layer: read from a real keyboard, with the three right-column keys put back
// to their printed legends (Home, PgUp, PgDn). Fn layer: as read from the same keyboard.

import type { KeyValue } from "../protocol/keycodes";

const SLOTS = 128;

function decode(hex: string): KeyValue[] {
  const out: KeyValue[] = [];
  for (let i = 0; i < SLOTS; i++) {
    const at = i * 8;
    out.push(at < hex.length ? [0, 2, 4, 6].map((o) => parseInt(hex.slice(at + o, at + o + 2), 16)) as KeyValue : [0, 0, 0, 0]);
  }
  return out;
}

